/// Inputs that must be rejected by every decoder under default options,
/// grouped by the rule they violate. Shared by the DateComponents and Date suites.
enum Corpus {
    static let unsupportedForms = [
        "",
        "2020",  // year only
        "2020-02",  // year-month
        "20",
        "2020-W05",  // week date
        "2020-W05-3",
        "2020W053",
        "2020-032",  // ordinal date
        "2020032",
        "T12:30Z",  // time without date
        "12:30:00",
        "12:30:00Z",
        "T",
        "Z",
    ]

    /// Defaults: date requires dashes, time requires colons
    static let basicFormat = [
        "20200202",
        "20200202T080034",
        "20200202T080034Z",
        "20200202T08:00:34Z",  // basic date, extended time
        "2020-02-02T080034Z",  // extended date, basic time
        "2020-02-02T0800Z",
        "2020-02-02T08:0034Z",
        "2020-02-02T0800:34Z",
        "2020-0202",
        "202002-02",
    ]

    static let fieldWidths = [
        "2020-2-02",
        "2020-02-2",
        "2020-2-2",
        "20-02-02",
        "202-02-02",
        "02020-02-02",  // 5-digit year
        "+2020-02-02",
        "-2020-02-02",
        "+002020-02-02",  // expanded year
        "-000001-01-01",
        "2020-002-02",
        "2020-02-002",
        "2020-02-02T8",
        "2020-02-02T8:00",
        "2020-02-02T08:0",
        "2020-02-02T08:00:3",
        "2020-02-02T123",
        "2020-02-02T08:000",
        "2020-02-02T08:00:345",
    ]

    static let truncated = [
        "2020-",
        "2020-02-",
        "2020-02-0",
        "2020-02-02T",
        "2020-02-02t",
        // "2020-02-02 ",
        "2020-02-02T08:",
        "2020-02-02T08:00:",
        "2020-02-02T08Z:",
    ]

    static let outOfRange = [
        "2020-00-02",
        "2020-13-02",
        "2020-99-02",
        "2020-02-00",
        "2020-02-32",
        "2020-01-99",
        "2020-02-02T24",
        "2020-02-02T24:00",
        "2020-02-02T24:00:00",  // ISO end-of-day: rejected
        "2020-02-02T24:00:00Z",
        "2020-02-02T25:00:00",
        "2020-02-02T99:00:00",
        "2020-02-02T08:60",
        "2020-02-02T08:60:00",
        "2020-02-02T08:99:00",
        "2020-02-02T23:59:60",  // leap second: rejected
        "2020-02-02T23:59:60Z",
        "2020-02-02T08:00:61",
        "2020-02-02T08:00:99",
    ]

    static let fractions = [
        "2020-02-02T08:00:34.",  // no digits
        "2020-02-02T08:00:34.Z",
        "2020-02-02T08:00:34,5",  // comma: rejected under the default `.dot`
        "2020-02-02T08:00:34,5Z",
        "2020-02-02T08:00:34.5.5",
        "2020-02-02T08:00:34..5",
        "2020-02-02T08:00:34.-5",
        "2020-02-02T08:00:34.+5",
        "2020-02-02T08:00:34. 5",
        "2020-02-02T08:00:34.5 ",
        "2020-02-02T08:00:34.5e3",
        "2020-02-02T08:00:34.0x1",
        "2020-02-02T12.5",  // fraction on hour
        "2020-02-02T12,5",
        "2020-02-02T12.5Z",
        "2020-02-02T12:30.5",  // fraction on minute
        "2020-02-02T12:30.5Z",
        "2020-02-02.5",  // fraction on day
        "2020-02-02T.5",
    ]

    static let separators = [
        "2020-02-02_08:00:34",
        "2020-02-02  08:00:34",  // two spaces
        "2020-02-02\t08:00:34",
        "2020-02-02\n08:00:34",
        "2020-02-02\u{00A0}08:00:34",  // NBSP
        "2020-02-02x08:00:34",
        "2020-02-02TT08:00:34",
        "2020-02-02Tt08:00:34",
        "2020-02-02T 08:00:34",
        "2020-02-0208:00:34",  // no separator
        "2020/02/02",
        "2020.02.02",
        "2020 02 02",
        "2020_02_02",
        "2020\u{2013}02\u{2013}02",  // en dash
        "2020\u{2010}02\u{2010}02",  // unicode hyphen
        "2020-02-02T08.00.34",
        "2020-02-02T08-00-34",
        "2020-02-02T08:00-34",
        "2020-02-02T08\u{FF1A}00\u{FF1A}34",  // fullwidth colon
        "2020-02--02",
        "2020--02-02",
        "2020-02-02T08::00",
    ]

    static let offsets = [
        // offsets on a bare date
        "2020-02-02Z",
        "2020-02-02z",
        "2020-02-02+05:00",
        "2020-02-02+05",
        "2020-02-02-0500",
        // hh:mm:ss is not in the default `timezone` set
        "2020-02-02T08:00:34+05:30:45",
        "2020-02-02T08:00:34+053045",
        "2020-02-02T08:00:34+05:30:00",
        // malformed
        "2020-02-02T08:00:34+5",
        "2020-02-02T08:00:34+5:30",
        "2020-02-02T08:00:34+05:3",
        "2020-02-02T08:00:34+05:",
        "2020-02-02T08:00:34+053",
        "2020-02-02T08:00:34+05300",
        "2020-02-02T08:00:34+05:30Z",
        "2020-02-02T08:00:34Z+05:00",
        "2020-02-02T08:00:34ZZ",
        "2020-02-02T08:00:34Zz",
        "2020-02-02T08:00:34+",
        "2020-02-02T08:00:34-",
        "2020-02-02T08:00:34++05:00",
        "2020-02-02T08:00:34+-05:00",
        "2020-02-02T08:00:34 +05:00",
        "2020-02-02T08:00:34 Z",
        "2020-02-02T08:00:34+05 :00",
        "2020-02-02T08:00:34+05.30",
        "2020-02-02T08:00:34+05:30.5",
        "2020-02-02T08:00:34\u{2212}05:00",  // U+2212 MINUS SIGN
        "2020-02-02T08:00:34\u{2013}05:00",  // en dash
        "2020-02-02T08:00:34\u{FF0B}05:00",  // fullwidth plus
        "2020-02-02T08:00:34UTC",
        "2020-02-02T08:00:34GMT",
        "2020-02-02T08:00:34utc",
        "2020-02-02T08:00:34[UTC]",
        "2020-02-02T08:00:34Z[UTC]",
        "2020-02-02T08:00:34+05h",
        // range: beyond ±18:00, minutes 00–59
        "2020-02-02T08:00:34+18:01",
        "2020-02-02T08:00:34-18:01",
        "2020-02-02T08:00:34+1801",
        "2020-02-02T08:00:34+19",
        "2020-02-02T08:00:34-19:00",
        "2020-02-02T08:00:34+23:59",
        "2020-02-02T08:00:34+24:00",
        "2020-02-02T08:00:34+99:00",
        "2020-02-02T08:00:34+05:60",
        "2020-02-02T08:00:34+05:99",
        "2020-02-02T08:00:34+0560",
    ]

    static let lexical = [
        " 2020-02-02T08:00:34Z",
        "2020-02-02T08:00:34Z ",
        "\t2020-02-02T08:00:34Z",
        "2020-02-02T08:00:34Z\n",
        "\n2020-02-02",
        "2020-02-02\n",
        "2020-02-02\r\n",
        "\u{FEFF}2020-02-02",  // BOM
        "2020-02-02\u{0}",
        "\u{0}2020-02-02",
        "2020-02-02T08:00\u{0}:34Z",
        "2020-02-02T08:00:34Zx",
        "2020-02-02T08:00:34x",
        "2020-02-02x",
        "2020-02-02T08:00:34Z2020-02-02T08:00:34Z",
        "\u{FF12}\u{FF10}\u{FF12}\u{FF10}-\u{FF10}\u{FF12}-\u{FF10}\u{FF12}",  // fullwidth digits
        "\u{0662}\u{0660}\u{0662}\u{0660}-\u{0660}\u{0662}-\u{0660}\u{0662}",  // Arabic-Indic digits
        "\u{096A}020-02-02",  // Devanagari digit
        "2020-02-0\u{00B2}",  // superscript two
        "2020-02-02T08:00:3\u{0034}\u{0301}Z",  // combining mark
        "202a-02-02",
        "2020-0a-02",
        "2020-02-0a",
        "2020-02-02T0a:00:34Z",
        "abcd-ef-gh",
        "2020-02-02T08:00:34z\u{0}",
        "２０２０-02-02",
    ]

    /// Every malformed input above, which decoders must reject under defaults
    static let malformed =
        unsupportedForms + basicFormat + fieldWidths + truncated + outOfRange
        + fractions + separators + offsets + lexical
}
